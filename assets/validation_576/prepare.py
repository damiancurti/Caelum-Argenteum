"""Build a deterministic, private native art gallery without IWAD content."""
from pathlib import Path
import json
import struct
import zipfile

ROOT=Path(__file__).resolve().parents[2]
HERE=Path(__file__).resolve().parent
OUT=ROOT/'build/issue471'
OUT.mkdir(parents=True,exist_ok=True)
manifest=json.loads((ROOT/'assets/generators/alchemy_ingredients_manifest.json').read_text(encoding='utf-8'))
text=['namespace="ZDoom";', 'sector { heightfloor=0; heightceiling=256; texturefloor="C471FLAT"; textureceiling="C471FLAT"; lightlevel=224; }']
for x,y in [(-512,-512),(-512,512),(2816,512),(2816,-512)]:text.append(f'vertex {{ x={x}; y={y}; }}')
for i in range(4):
    text+=['sidedef { sector=0; texturemiddle="C471WALL"; }',f'linedef {{ v1={i}; v2={(i+1)%4}; sidefront={i}; blocking=true; }}']
text.append('thing { x=0; y=0; angle=0; type=1; skill1=true; skill2=true; skill3=true; skill4=true; skill5=true; single=true; coop=true; dm=true; }')
lumps=[('CART471',b''),('TEXTMAP','\n'.join(text).encode()),('ENDMAP',b'')]
body=b'';directory=b''
for name,data in lumps:
    directory+=struct.pack('<ii8s',12+len(body),len(data),name.encode().ljust(8,b'\0'));body+=data
wad=b'PWAD'+struct.pack('<ii',len(lumps),12+len(body))+body+directory
classes=[];models=[];setup=[]
textures=['Texture C471FLAT, 64, 64 { Patch "models/caelum/world/alchemy_ingredients/host.png", 0, 0 }',
          'Texture C471WALL, 64, 64 { Patch "models/caelum/props/stations/ca_station_wood.png", 0, 0 }']
for i,spec in enumerate(manifest['assets']):
    frame=f'Q{i:03d}'
    classes.append(f'class CA471Art{i} : Actor {{ Default {{ +NOGRAVITY +NOBLOCKMAP +NOBLOCKMONST +NOINTERACTION }} States {{ Spawn: {frame} A -1; Stop; }} }}')
    path=Path(spec['model'])
    models.append(f'Model CA471Art{i} {{ Path "{path.parent.as_posix()}" Model 0 "{path.name}" Scale 1 1 1 CorrectPixelStretch DontCullBackFaces FrameIndex {frame} A 0 0 }}')
    textures.append(f'Sprite "{frame}A0", 128, 128 {{ Offset 64, 128 Patch "{spec["icon"]}", 0, 0 }}')
    setup.extend([f'Objects[{i}]=Actor.Spawn("CA471Art{i}",({i*224},0,0),NO_REPLACE);',
                  f'Names[{i}]="{spec["es"]}"; Icons[{i}]="{spec["icon"]}";',
                  f'Console.Printf("CA471 %s model {spec["key"]}",Objects[{i}]!=null?"PASS":"FAIL");'])
setup.extend(['let item=CaelumMaterialPickup(Actor.Spawn("CaelumMaterialPickup",u.Pos,NO_REPLACE));',
              'item.args[0]=88;item.args[1]=1;item.Amount=1;item.UpdateMaterialVisuals();item.AttachToOwner(u);u.OnNativeInventoryChanged();',
              'Console.Printf("CA471 %s live iodine icon",CaelumMarineData.MaterialIcon(88)=="graphics/caelum/icons/materials/ca_material_iodine.png"?"PASS":"FAIL");',
              'Console.Printf("CA471 RESULT artwork gallery ready");'])
gallery=(HERE/'gallery.zs').read_text(encoding='utf-8').replace('// SETUP GENERATED BY prepare.py','\n'.join(setup))
members={'ZSCRIPT':('version "4.14"\n'+'\n'.join(classes)+'\n'+gallery).encode(),
         'MAPINFO':b'GameInfo { AddEventHandlers="CA471Gallery" }\nmap CART471 "Alchemy art gallery" { }\n',
         'MODELDEF':'\n'.join(models).encode(),'TEXTURES':'\n'.join(textures).encode(),'maps/CART471.wad':wad}
with zipfile.ZipFile(OUT/'gallery.pk3','w',zipfile.ZIP_STORED) as package:
    for key,data in sorted(members.items()):package.writestr(zipfile.ZipInfo(key,(2000,1,1,0,0,0)),data)
scripts={'smoke':'wait 70; netevent ca471_setup; wait 15; quit',
         'inventory':f'wait 70; netevent ca471_setup; wait 15; netevent ca471_inventory; wait 15; screenshot "{OUT.as_posix()}/iodine-inventory.png"; wait 5; quit',
         'interactive':'bind w +forward; bind s +back; bind a +moveleft; bind d +moveright; bind f1 "netevent ca471_next"; bind f2 "netevent ca471_view"; bind f3 "netevent ca471_previous"; bind f4 "netevent ca471_inventory"; bind q ca_journal; language es; wait 70; netevent ca471_setup',
         'gallery':f'wait 70; netevent ca471_setup; wait 10; exec "{OUT.as_posix()}/view-0.cfg"'}
for i,spec in enumerate(manifest['assets']):
    commands=[f'netevent ca471_select {i} {v}; wait 10; screenshot "{OUT.as_posix()}/{spec["key"]}-{v}.png"' for v in (0,1,2)]
    commands.append(f'wait 5; exec "{OUT.as_posix()}/view-{i+1}.cfg"' if i<10 else 'wait 5; quit')
    scripts[f'view-{i}']='; '.join(commands)
for name,data in scripts.items():(OUT/f'{name}.cfg').write_text(data+'\n',encoding='utf-8',newline='\n')
print('Prepared independent #471 art gallery: 11 models and matching icons.')
