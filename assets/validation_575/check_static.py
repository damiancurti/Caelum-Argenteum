"""Check #407 authored data, model provenance and deterministic outputs."""
from pathlib import Path
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'build/issue407'
data=json.loads((ROOT/'assets/generators/marine_resources.json').read_text(encoding='utf-8'))
constants=(ROOT/'src/caelum/core/CaelumConstants.zs').read_text(encoding='utf-8')
registry=(ROOT/'src/caelum/equipment/CaelumSpecialItems.zs').read_text(encoding='utf-8')
for row in data['materials']:
    assert re.search(rf'const MATERIAL_{row["symbol"]}\s*=\s*{row["id"]};',constants)
    assert f'M{row["id"]:03d} A 0;' in registry
    assert (ROOT/f'src/graphics/caelum/icons/materials/ca_material_{row["icon"]}.png').is_file()
assert data['recipe']=={'id':168,'input_grams':100,'theoretical_output_grams':1,'base_work_seconds':60,'additional_fuel_grams':0}
paths=[ROOT/'src/caelum/data/CaelumMarineData.zs',ROOT/'src/LANGUAGE',
       ROOT/'src/caelum/data/marine_resources.modeldef',ROOT/'src/caelum/data/marine_resources.textures',
       ROOT/'assets/generators/marine_models.json',*sorted((ROOT/'src/models/caelum/world/marine_resources').glob('*.obj'))]
def hashes():return {p.relative_to(ROOT).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}
before=hashes()
for repeat in range(2):
    for generator in ['generate_marine_resources.py','generate_marine_models.py']:
        subprocess.run([sys.executable,str(ROOT/'assets/generators'/generator)],cwd=ROOT,check=True)
    assert hashes()==before, 'Generated bytes changed'
manifest=json.loads((ROOT/'assets/generators/marine_models.json').read_text(encoding='utf-8'))
for name in manifest['textures']:assert (ROOT/'src'/name).is_file()
for row in manifest['models']:
    text=(ROOT/'src/models/caelum/world/marine_resources'/row['file']).read_text(encoding='utf-8')
    assert len(re.findall(r'^v ',text,re.M))==row['vertices']
    assert len(re.findall(r'^f ',text,re.M))==row['faces']
    for texture in re.findall(r'^usemtl (.+)$',text,re.M):assert (ROOT/'src'/texture).is_file()
OUT.mkdir(parents=True,exist_ok=True)
(OUT/'determinism.json').write_text(json.dumps({'iterations':2,'hashes':before,'models':manifest['models']},indent=2)+'\n',encoding='utf-8',newline='\n')
print('PASS: approved data, IDs, registered sprites, owned textures and two byte-identical generations.')
