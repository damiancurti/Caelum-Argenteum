"""Verify reproducible new assets and unchanged accepted ram mass inputs."""
from pathlib import Path
import hashlib,importlib,json,subprocess,sys

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'assets/generators'))
from generate_ram_runtime import component_volumes,DATA,U

def hashes():
    paths=['src/MODELDEF','src/caelum/data/CaelumMachineMaterials.zs','src/models/caelum/siege/ca_barricade.obj']
    return {p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in paths}

if __name__=='__main__':
    before=hashes()
    for _ in range(2):
        subprocess.run([sys.executable,'assets/generators/generate_machine_runtime.py'],cwd=ROOT,check=True,capture_output=True)
        assert hashes()==before,'Generated bytes changed on a repeat invocation'
    mw,mi,fw,fi=component_volumes()
    moving=(mw*DATA['oak_kg_m3']+mi*DATA['iron_kg_m3'])/U**3
    frame=(fw*DATA['oak_kg_m3']+fi*DATA['iron_kg_m3'])/U**3
    original=json.loads((ROOT/'assets/validation_43616/ram_inputs.json').read_text(encoding='utf-8'))['derived']
    assert abs(moving-original['MOVING_MASS'])<1e-9
    assert abs(frame-original['FRAME_MASS'])<1e-9
    result=dict(passed=True,hashes=before,moving_mass=moving,frame_mass=frame,original_masses_preserved=True)
    (Path(__file__).parent/'generator-results.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result))
