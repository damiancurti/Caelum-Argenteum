"""Register the 75 additional owned Tarot fronts without modifying their pixels."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    cards = json.loads((ROOT / "assets/manifests/tarot_78_v4369.json").read_text(encoding="utf-8"))["cards"]
    textures = ["// Generated by assets/generators/tarot_world_fronts.py; owned #15 art."]
    states = ["// Registro previo al render; no altera estados de actores guardados.",
              "class CaelumArcanaFronts : Actor", "{", "    States", "    {", "    Spawn:",
              "        TNT1 A -1;", "        Stop;", "    RegisteredFronts:"]
    for card in cards:
        number = card["card_id"]
        if number in (0, 36, 60):
            continue
        sprite = f"TA{number:02d}"
        path = card["runtime_path"].removeprefix("src/")
        textures.append(f'Sprite "{sprite}A0", 1024, 1536\n{{\n    XScale 8\n    YScale 8\n    Offset 512, 1536\n    Patch "{path}", 0, 0\n}}')
        states.append(f"        {sprite} A -1;")
    states.extend(["        Stop;", "    }", "}"])
    (ROOT / "src/caelum/data/tarot_fronts.textures").write_text("\n".join(textures)+"\n", encoding="utf-8", newline="\n")
    (ROOT / "src/caelum/quests/CaelumArcanaFronts.zs").write_text("\n".join(states)+"\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
