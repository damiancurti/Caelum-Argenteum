"""Build persistent owned transit interiors and geographically keyed stops."""
from pathlib import Path
import json
import sys
sys.dont_write_bytecode = True
from generate_coastal_trials import CoastalMap

ROOT = Path(__file__).resolve().parents[2]

def generate():
    data = json.loads((ROOT / 'assets/transport/scenes.json').read_text(encoding='utf-8'))
    network = json.loads((ROOT / 'assets/transport/network.json').read_text(encoding='utf-8'))
    entries = []
    for index in range(data['rural_count']):
        entries.append((f'CAR{index:02}', True))
    for route in network['routes']:
        for mode in range(3, 7):
            entries.append((f'CAT{mode}{route["id"]:02}', False))
    maps = []
    for name, rural in entries:
        scene = CoastalMap(name)
        scene.compact = scene.optimize_open_geometry = True
        scene.add_default_things = False
        stage = None if rural else data['stages'][name[3]]
        bounds = data['rural_bounds'] if rural else stage['bounds']
        roof = 0 if rural else stage['roof']
        if roof:scene.volume(200,roof,roof+8,data['deck_flat'],data['wall'])
        scene.room(*bounds, flat=data['ground_flat'] if rural else data['deck_flat'], wall=data['wall'],volume=200 if roof else 0)
        x1,y1,x2,y2 = bounds
        for rectangle in [(x1-64,y1-64,x2+64,y1),(x1-64,y2,x2+64,y2+64),
                          (x1-64,y1,x1,y2),(x2,y1,x2+64,y2)]:
            scene.room(*rectangle, floor=data['boundary_height'], flat=data['deck_flat'], wall=data['wall'])
        if rural:
            scene.room(*data['rural_road'], flat=data['road_flat'], wall=data['wall'])
        x,y,angle = data['rural_spawn'] if rural else data['stage_spawn']
        scene.prop(1,x,y,angle)
        scene.prop(30950,x,y+64,args=(1,0))
        scene.write(ROOT / 'src/maps')
        key = 'CA_TRANSPORT_COUNTRY' if rural else 'CA_TRANSPORT_ONBOARD'
        maps.append(f'map {name} "${key}" {{ cluster={data["cluster"]} sky1="CABASKY",0 music="" nointermission UnFreezeSinglePlayerConversations }}')
    (ROOT/'src/caelum/data/transport_scenes.mapinfo').write_text('\n'.join(maps)+'\n',encoding='utf-8')
    source = f'''// Generated by generate_transport_scenes.py; geometry only, no travel balance.
class CaelumTransportSceneData : Object
{{
    const REVISION={data['revision']};
    const RURAL_INTERVAL_KM={data['rural_interval_km']};
    const RURAL_COUNT={data['rural_count']};
    static clearscope String Stage(int route,int mode){{return String.Format("CAT%d%02d",mode,route);}}
    static clearscope String Rural(int index){{return String.Format("CAR%02d",Clamp(index,0,RURAL_COUNT-1));}}
    static clearscope bool IsStage(String map){{return map.Left(3)=="CAT" && map.Length()==6;}}
    static clearscope bool IsRural(String map){{return map.Left(3)=="CAR" && map.Length()==5;}}
    static clearscope vector3 RuralEntry(){{return ({data['rural_spawn'][0]},{data['rural_spawn'][1]},0);}}
    static clearscope vector3 AccessPosition(){{return ({','.join(map(str,data['access_position']))});}}
    static clearscope bool BlocksRuralAccess(vector3 point,double radius)
    {{return point.X+radius>{data['rural_access_bounds'][0]} && point.X-radius<{data['rural_access_bounds'][2]}
        && point.Y+radius>{data['rural_access_bounds'][1]} && point.Y-radius<{data['rural_access_bounds'][3]};}}
    static clearscope String GroundFlat(){{return "{data['ground_flat']}";}}
    static clearscope int TreeCount(){{return {len(data['trees'])};}}
    static clearscope vector3 Tree(int index)
    {{vector3 positions[]={{{','.join('('+str(x)+','+str(y)+',0)' for x,y in data['trees'])}}};return positions[Clamp(index,0,{len(data['trees'])-1})];}}
}}
'''
    (ROOT/'src/caelum/data/CaelumTransportSceneData.zs').write_text(source,encoding='utf-8')
    print(f'Generated {len(entries)} persistent transport scenes')

if __name__ == '__main__':
    generate()
