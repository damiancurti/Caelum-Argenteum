"""Register the original #163 atlas with deterministic native TEXTURES crops."""
from pathlib import Path
import json
import shutil

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'assets/source/art/bolas_5116'
DEST = ROOT / 'src/graphics/caelum/bolas'


def main():
    data = json.loads((SOURCE / 'DESIGN.json').read_text(encoding='utf-8'))
    DEST.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(SOURCE / data['source'], DEST / 'atlas.png')
    ready = data['hanging_ready']
    shutil.copyfile(SOURCE / ready['source'], DEST / ready['source'])
    lines = ['// Generated by assets/generators/register_bolas.py.']
    for i, (x, y, w, h) in enumerate(data['cells']):
        lines.append(f'Graphic "CABOL_CELL_{i}", {w}, {h} {{ Patch "graphics/caelum/bolas/atlas.png", {-x}, {-y} }}')
    for i, (gx, gy) in enumerate(data['grips']):
        if i == 0:
            gx, gy = ready['grip']
            scale = ready['scale']
            px, py = 216 * scale, 160 * scale
            lines.append(f'Sprite "DBOLA0", {320*scale}, {320*scale} {{ XScale {scale} YScale {scale} NoTrim Offset {px}, {py} Patch "graphics/caelum/bolas/{ready["source"]}", {px-gx}, {py-gy} }}')
            continue
        cell = i if i < 3 else 0
        lines.append(f'Sprite "DBOL{chr(65+i)}0", 1280, 800 {{ XScale 4 YScale 4 NoTrim Offset 864, 640 Graphic "CABOL_CELL_{cell}", {864-gx}, {640-gy} }}')
    lines.append('Graphic "CA_BOLAS_ICON", 426, 640 { XScale 5 YScale 5 Graphic "CABOL_CELL_3", 0, 0 }')
    lines.append('Sprite "CBOLA0", 426, 640 { XScale 5 YScale 5 Offset 213, 530 Graphic "CABOL_CELL_3", 0, 0 }')
    lines.append('Sprite "CBOLB0", 427, 640 { XScale 20 YScale 20 Offset 213, 320 Graphic "CABOL_CELL_2", 0, 0 }')
    for i, split in enumerate(data['wrap_split_rows']):
        lines.append(f'Graphic "CABOL_FRONT_{i}", 427, {640-split} {{ Graphic "CABOL_CELL_{4+i}", 0, {-split} }}')
        lines.append(f'Graphic "CABOL_BACK_{i}", 427, {split} {{ Graphic "CABOL_CELL_{4+i}", 0, 0 }}')
        lines.append(f'Sprite "CBND{chr(65+i)}0", 427, 640 {{ XScale 3.3359375 YScale 3.3359375 Offset 213, 300 Graphic "CABOL_FRONT_{i}", 0, {split} }}')
        lines.append(f'Sprite "CBND{chr(67+i)}0", 427, 640 {{ XScale 3.3359375 YScale 3.3359375 Offset 213, 300 Graphic "CABOL_BACK_{i}", 0, 0 }}')
    (DEST / 'bolas.textures').write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
