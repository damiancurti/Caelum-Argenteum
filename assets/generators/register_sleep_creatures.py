"""Register the owned #238 sleeping paintings without repainting anatomy.

Optional dependency: Pillow 11.3.0. Source selection and visual calibration live
in sleep_creatures.json. No source, existing sprite or gameplay dimension changes.
"""
from pathlib import Path
import hashlib
import json
from PIL import Image
from appearance_pose_modules import clean, save_png

ROOT = Path(__file__).resolve().parents[2]
SPEC = json.loads(Path(__file__).with_name('sleep_creatures.json').read_text())
SOURCE = ROOT / 'assets/source/art/sleep_544'
OUTPUT = ROOT / 'src/graphics/caelum/sleep_creatures'


def silhouettes(image):
    """Locate bodies independently of equal-cell boundaries and stray pixels."""
    w, h = image.size
    seen = bytearray(image.getchannel('A').point(lambda a: 255 if a >= 64 else 0).tobytes())
    parts = []
    for start in range(len(seen)):
        if not seen[start]:
            continue
        pending = [start]
        seen[start] = 0
        area = 0
        x0 = x1 = start % w
        y0 = y1 = start // w
        while pending:
            i = pending.pop()
            x, y = i % w, i // w
            area += 1
            x0, x1, y0, y1 = min(x0, x), max(x1, x), min(y0, y), max(y1, y)
            for n in (i-1 if x else -1, i+1 if x<w-1 else -1,
                      i-w if y else -1, i+w if y<h-1 else -1):
                if n >= 0 and seen[n]:
                    seen[n] = 0
                    pending.append(n)
        if area >= SPEC['minimum_body_pixels']:
            parts.append((area, (x0, y0, x1+1, y1+1)))
    assert len(parts) == 8, ('Expected eight separated bodies', parts)
    parts.sort(key=lambda p: (sum(p[1][1::2])//h, p[1][0]))
    pad = SPEC['crop_padding']
    return [(max(0,a-pad), max(0,b-pad), min(w,c+pad), min(h,d+pad))
            for _, (a,b,c,d) in parts]


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    lines = ['// Generated by assets/generators/register_sleep_creatures.py.']
    report = {'issue': 238, 'version': '5.4.4', 'tool': 'built-in image_gen', 'actors': {}}
    common = json.loads((ROOT/'assets/generators/appearance_catalog.json').read_text())
    projection = common['authored_registration']['sleep']
    for key, data in SPEC['actors'].items():
        path = SOURCE/data['source']
        original = Image.open(path).convert('RGBA')
        boxes = silhouettes(original)
        crops = [clean(original.crop(b)) for b in boxes]
        records = []
        for view, raw in enumerate(crops):
            if data['supine']:
                target = data['reference_length'] * projection['length'][view]/projection['length'][2]
                scale = target/max(raw.size)
                depth = projection['body_projection'][view]
            else:
                scale = data['reference_length']/crops[2].width
                depth = 1
            size = (max(1, round(raw.width*scale)), max(1, round(raw.height*scale*depth)))
            result = clean(raw.resize(size, Image.Resampling.LANCZOS))
            name = f'{key}-{view+1}.png'
            save_png(result, OUTPUT/name)
            bounds = result.getchannel('A').getbbox()
            pivot = [(bounds[0]+bounds[2])//2, bounds[3]]
            sprite = f"{data['sprite']}A{view+1}"
            lines.append(f'Sprite "{sprite}", {size[0]}, {size[1]} {{ XScale {data["texture_scale"]} YScale {data["texture_scale"]} Offset {pivot[0]}, {pivot[1]} Patch "graphics/caelum/sleep_creatures/{name}", 0, 0 }}')
            records.append({'sprite': sprite, 'source_rect': boxes[view], 'size': size,
                            'pivot': pivot, 'sha256': hashlib.sha256((OUTPUT/name).read_bytes()).hexdigest()})
        report['actors'][key] = {'source': data['source'], 'source_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                                 'reference': data['reference'], 'reference_length': data['reference_length'], 'frames': records}
    text = '\n'.join(lines)+'\n'
    (OUTPUT/'sleep.textures').write_text(text, encoding='utf-8', newline='\n')
    (ROOT/'assets/validation_544/sleep_art.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8', newline='\n')
    print('Registered 32 sleeping views; original artwork and gameplay dimensions unchanged.')


if __name__ == '__main__':
    main()
