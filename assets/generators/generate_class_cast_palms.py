"""Extract the correct owned atlas rows for #238; leave accepted weapon art intact.

Pillow 11.3.0. Reuses the existing deterministic registration/tint pipeline.
The male atlas rows are not equal-height tiles. The last row contains the palms;
including the preceding row's wrist produces detached strips and shrinks the hand.
"""
import hashlib
import json
from pathlib import Path

from PIL import Image
from generate_appearance_hands import clean, fit, tinted
from appearance_pose_modules import save_png

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(__file__).with_name("class_cast_palms.json")


def main():
    data = json.loads(DATA.read_text(encoding="utf-8"))
    records = {}
    sources = {}
    textures = ["// Generated by generate_class_cast_palms.py; existing weapon hands remain unchanged."]
    states = ["// Generado por generate_class_cast_palms.py.",
              "class CaelumClassCastHandFrames : Actor", "{", "    States (Weapon, Overlay)", "    {"]
    for family, art in enumerate(data["families"]):
        source = ROOT / data["source_directory"] / f"first_person_bare_{art}_v1.png"
        sources[source.relative_to(ROOT).as_posix()] = hashlib.sha256(source.read_bytes()).hexdigest()
        atlas = clean(Image.open(source))
        top, bottom = data["last_row"][art]
        for tone in range(3):
            variant = family * 3 + tone
            for side, hand in enumerate(data["hands"]):
                cell = atlas.crop((side * atlas.width // 2, top, (side + 1) * atlas.width // 2, bottom))
                reference = Image.open(ROOT / f"src/sprites/caelum/first_person/v1/hands/FH{hand:02d}A0.png").convert("RGBA")
                result, _ = tinted(fit(cell, reference), family, tone)
                path = ROOT / f"src/graphics/caelum/class_cast/{variant}_{side}.png"
                path.parent.mkdir(parents=True, exist_ok=True)
                save_png(result, path)
                records[path.relative_to(ROOT).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
                prefix = f"J{variant:02d}{side}"
                x, y = data["pivots"][side]
                textures.append(f'Sprite "{prefix}A0", 320, 200\n{{\n    NoTrim\n    Offset {x}, {y}\n    Patch "{path.relative_to(ROOT / "src").as_posix()}", 0, 0\n}}')
                states.append(f"    V{variant}_{side}: {prefix} A -1; Stop;")
    states += ["    }", "}"]
    outputs = {
        ROOT / "src/graphics/caelum/class_cast.textures": "\n\n".join(textures) + "\n",
        ROOT / "src/caelum/character/CaelumClassCastHandFrames.zs": "\n".join(states) + "\n",
    }
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8", newline="\n")
        records[path.relative_to(ROOT).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    manifest = {"issue": 238, "source_provenance": "assets/source/art/appearance_5213/PROVENANCE.json",
                "method": "Correct last-row extraction, existing fit/tint/PNG pipeline; no source art edits.",
                "sources": sources, "outputs": records, "author_acceptance": "Pending; component is in progress."}
    path = ROOT / "assets/validation_544/palms.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Registered {len(records)} deterministic outputs; existing weapon modules unchanged.")


if __name__ == "__main__":
    main()
