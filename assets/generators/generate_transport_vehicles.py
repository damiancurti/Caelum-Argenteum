"""Register the authored horse atlas and build the owned steam-train mesh."""
from pathlib import Path
import json
import math
import struct
import sys
from PIL import Image, PngImagePlugin
sys.dont_write_bytecode = True
from generate_station_models import Mesh, material
from generate_stash_models import WOOD

ROOT = Path(__file__).resolve().parents[2]

def generate():
    data=json.loads((ROOT/'assets/transport/vehicles.json').read_text(encoding='utf-8'))
    atlas=Image.open(ROOT/data['horse_atlas']).convert('RGBA')
    output=ROOT/'src/sprites/caelum/transport'
    output.mkdir(parents=True,exist_ok=True)
    for index in range(8):
        row,column=divmod(index,4)
        image=atlas.crop((data['horse_columns'][column],data['horse_rows'][row],data['horse_columns'][column+1],data['horse_rows'][row+1]))
        image=image.crop(image.getchannel('A').getbbox())
        size=tuple(round(value*data['horse_scale_pixels']) for value in image.size)
        image=image.resize(size,Image.Resampling.LANCZOS)
        # Preserve painted pixels, real alpha and a consistent hoof origin.
        info=PngImagePlugin.PngInfo();info.add(b'grAb',struct.pack('>ii',image.width//2,image.height))
        image.save(output/f'CHRSA{index+1}.png',pnginfo=info,optimize=False)
    mesh=Mesh('CaelumSteamPassengerService')
    for x in (-26.8,26.8):mesh.box('iron',(x,2,0),(3,4,800))
    for z in range(-392,393,24):mesh.box('wood',(0,0,z),(80,3,8))
    # X lateral, Y vertical, Z along the train; all dimensions are MU.
    mesh.box('iron',(0,30,-172),(78,12,328))
    mesh.rod('iron',(0,76,-316),(0,76,-124),30,30,20)
    mesh.rod('brass',(0,77,-318),(0,77,-316),29,29,20)
    mesh.rod('iron',(0,100,-270),(0,148,-270),9,13,12)
    mesh.ball('brass',(0,108,-174),(13,12,13),4,12)
    mesh.box('wood',(0,55,-84),(80,44,72))
    for x in (-37,37):
        for z in (-118,-50):mesh.rod('iron',(x,60,z),(x,126,z),2,2,4)
    mesh.box('iron',(0,130,-84),(86,6,80))
    mesh.box('wood',(0,60,0),(76,60,64))
    mesh.box('iron',(0,92,0),(68,6,56))
    # Coach with open windows, roof, benches and end steps.
    mesh.box('wood',(0,36,224),(82,10,256))
    for x in (-40,40):
        mesh.box('wood',(x,61,224),(4,42,256))
        mesh.box('wood',(x,120,224),(4,10,256))
        for z in range(96,353,32):mesh.box('wood',(x,100,z),(4,38,4))
    for z in (96,352):mesh.box('wood',(0,84,z),(80,88,4))
    for i in range(12):
        a=math.pi*i/12;b=math.pi*(i+1)/12
        mesh.add_quad(material('iron'),[(44*math.cos(a),124+12*math.sin(a),92),(44*math.cos(b),124+12*math.sin(b),92),(44*math.cos(b),124+12*math.sin(b),356),(44*math.cos(a),124+12*math.sin(a),356)])
    for z in range(116,341,40):
        for x in (-22,22):mesh.box('leather',(x,55,z),(30,8,24))
    for z in (-292,-228,-164,0,128,320):
        mesh.rod('iron',(-44,22,z),(44,22,z),3,3,8)
        for x in (-44,44):
            mesh.ring('iron',(x,22,z),20,2,'yz',20)
            for i in range(8):
                a=math.tau*i/8
                mesh.rod('iron',(x,22,z),(x,22+18*math.cos(a),z+18*math.sin(a)),1,1,4)
    mesh.vertices=[(x,y*1.2,z) for x,y,z in mesh.vertices]
    mesh.faces=[(WOOD if kind==material('wood') else kind,face) for kind,face in mesh.faces]
    mesh.faces.sort(key=lambda entry:entry[0])
    mesh.write(ROOT/'src/models/caelum/vehicles/ca_steam_train.obj')
    sign=Mesh('CaelumTransportAccessSign')
    sign.box('wood',(0,32,0),(5,64,5))
    sign.box('wood',(0,56,0),(52,28,4))
    sign.ring('brass',(0,56,-2.5),10,1,'xy',16)
    for i in range(6):
        angle=math.tau*i/6
        sign.rod('brass',(0,56,-3),(9*math.cos(angle),56+9*math.sin(angle),-3),.6,.6,4)
    sign.vertices=[(x,y*1.2,z) for x,y,z in sign.vertices]
    sign.faces=[(WOOD if kind==material('wood') else kind,face) for kind,face in sign.faces]
    sign.faces.sort(key=lambda entry:entry[0]);sign.write(ROOT/'src/models/caelum/vehicles/ca_transport_sign.obj')
    (ROOT/'src/caelum/data/transport_vehicles.modeldef').write_text('''Model CaelumSteamTrain
{
    Path "models/caelum/vehicles"
    Model 0 "ca_steam_train.obj"
    Scale 1 1 1
    AngleOffset 90
    CorrectPixelStretch
    DontCullBackFaces
    FrameIndex CAHC A 0 0
}
Model CaelumTransportSignVisual
{
    Path "models/caelum/vehicles"
    Model 0 "ca_transport_sign.obj"
    Scale 1 1 1
    AngleOffset 90
    CorrectPixelStretch
    DontCullBackFaces
    FrameIndex CSSG A 0 0
}
''',encoding='utf-8')
    lines=['// Generated by generate_transport_vehicles.py.','class CaelumTransportVehicleData : Object','{']
    lines += [f'    const TRAIN_HALF_LENGTH={data["train_half_length_mu"]};',f'    const TRAIN_HALF_WIDTH={data["train_half_width_mu"]};',f'    const TRAIN_HEIGHT={data["train_height_mu"]};']
    lines += [f'    static clearscope vector3 TrainBoarding(){{return ({",".join(map(str,data["train_boarding_mu"]))});}}']
    lines += ['    static clearscope vector3 Position(String map,int mode)','    {']
    for name,positions in data['positions'].items():
        lines += [f'        if(map=="{name}")','        {']
        for kind,position in positions.items():
            mode={'cart':3,'ship':4,'horse':5,'train':6}[kind]
            lines += [f'            if(mode=={mode})return ({",".join(map(str,position))});']
        lines += ['        }']
    lines += ['        return (0,0,0);','    }','}']
    (ROOT/'src/caelum/data/CaelumTransportVehicleData.zs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print('Registered 8 horse rotations and the steam service mesh')

if __name__=='__main__':generate()
