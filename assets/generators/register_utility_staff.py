"""Register the original #162 atlas without modifying raster pixels."""
from pathlib import Path
import hashlib
import json
import shutil

ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'assets/source/art/utility_staff_5115'
DEST=ROOT/'src/graphics/caelum/utility_staff'

def main():
    data=json.loads((SOURCE/'DESIGN.json').read_text(encoding='utf-8'))
    DEST.mkdir(parents=True,exist_ok=True)
    shutil.copyfile(SOURCE/data['source'],DEST/'atlas.png')
    lines=['// Generated by assets/generators/register_utility_staff.py.']
    scale=data['view_scale']; cell=data['cell'][0]
    for i,grip in enumerate(data['grips']):
        x=(i%2)*cell;y=(i//2)*cell
        lines.append(f'Graphic "CAUST_CELL_{i}", {cell}, {cell} {{ Patch "graphics/caelum/utility_staff/atlas.png", {-x}, {-y} }}')
        ox=data['view_grip'][0]*scale-grip[0];oy=data['view_grip'][1]*scale-grip[1]
        lines.append(f'Sprite "DUST{chr(65+i)}0", {320*scale}, {200*scale} {{ XScale {scale} YScale {scale} NoTrim Offset {216*scale}, {160*scale} Graphic "CAUST_CELL_{i}", {ox}, {oy} }}')
    lines += [f'Graphic "CA_UTILITY_STAFF_ICON", {cell}, {cell} {{ XScale {cell/128} YScale {cell/128} Graphic "CAUST_CELL_0", 0, 0 }}',
              f'Sprite "CUSTA0", {cell}, {cell} {{ XScale {cell/128} YScale {cell/128} Offset {cell//2}, 556 Graphic "CAUST_CELL_0", 0, 0 }}']
    (DEST/'staff.textures').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    print('Registered original utility staff:',hashlib.sha256((DEST/'atlas.png').read_bytes()).hexdigest())

if __name__=='__main__':main()
