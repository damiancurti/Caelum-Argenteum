"""Check six native crafting bases, closed solids, real holes and preserved bindings."""
import hashlib,json,struct
from PIL import Image
try:
    from .validate_inventory_ammunition_models import ROOT,validate as validate_family
    from .validate_inventory_weapon_components_models import inspect_geometry
except ImportError:
    from validate_inventory_ammunition_models import ROOT,validate as validate_family
    from validate_inventory_weapon_components_models import inspect_geometry


def validate(root=ROOT):
    errors=validate_family(root,'magic_bases',6,distinct_classes=False)
    try:
        source=root/'assets/source/art/inventory_models_647/magic_bases';config=json.loads((source/'DESIGN.json').read_text());report=json.loads((source/'EXPORT.json').read_text())
        bindings=[(36,'CSTF'),(37,'CBEL'),(39,'CSTA'),(44,'M044'),(89,'M089'),(90,'M090')]
        if [(v['item_type'],v['sprite']) for v in config['variants'].values()]!=bindings:errors.append('Unexpected magical material identities')
        if any(v['class']!='CaelumMaterialPickup' for v in config['variants'].values()):errors.append('Replacement outside material scope')
        if config['runtime_cases']!=[dict(item_type=n,tier=t) for n,s in bindings for t in [1,2,3]]:errors.append('Changed material tier cases')
        for name,checksum in report['sha256'].items():
            if name.startswith('editable/') and hashlib.sha256((source/name).read_bytes()).hexdigest()!=checksum:errors.append('Stale portable mesh '+name)
        texture='models/caelum/inventory/magic_bases/materials.png';blob=(source/'materials.png').read_bytes()
        if any(p.read_bytes()!=blob for p in [root/'src'/texture,source/'editable/src'/texture]):errors.append('Changed copied material atlas')
        prompt=json.loads((source/'MATERIALS_PROMPT.json').read_text())
        if hashlib.sha256(blob).hexdigest()!=prompt['sha256']:errors.append('Atlas differs from original generated bytes')
        image=Image.open(source/'materials.png').convert('RGBA')
        for settings in config['materials'].values():
            a,b,c,d=settings['rect_pixels']
            if image.getchannel('A').crop((max(0,a-1),max(0,b-1),min(image.width,c+1),min(image.height,d+1))).getextrema()!=(255,255):errors.append('Transparent material interior')
        for kind in config['variants']:
            more,_=inspect_geometry(root,kind,'magic_bases');errors.extend(kind+': '+e for e in more)
        shell=next(p for p in config['families']['censer']['parts'] if p['part']=='shell')
        if shell['kind']!='perforated_shell' or len(shell['holes'])!=48 or shell['genus']!=49:errors.append('Censer perforations missing')
        if len(config['families']['bell']['openings'])!=2 or len(config['families']['censer']['openings'])!=4:errors.append('Cavity probe coverage missing')
        for name in ['bell','censer']:
            regions=config['families'][name]['parts'][0]['surface_regions'];blob=(root/'src'/config['model_path']/(name+'.md3')).read_bytes();head=struct.unpack_from('<4sI64s9I',blob);offset=head[10];seen=set()
            for surface in report['variants'][name]['surfaces']:
                h=struct.unpack_from('<4s64s10I',blob,offset)
                if surface['material']==name+'_surface':
                    uv=[struct.unpack_from('<2f',blob,offset+h[9]+i*8) for i in range(h[5])]
                    for i in range(h[6]):
                        points=[uv[k] for k in struct.unpack_from('<3I',blob,offset+h[7]+i*12)]
                        cells=[key for key,(a,b,c,d) in regions.items() if all(a-1e-6<=u<=c+1e-6 and b-1e-6<=v<=d+1e-6 for u,v in points)]
                        if len(cells)!=1:errors.append(name+': triangle crosses atlas cells')
                        seen.update(cells)
                offset+=h[-1]
            if seen!={'inner','outer'}:errors.append(name+': missing dark cavity or outer material')
    except (OSError,ValueError,KeyError,struct.error) as exc:errors.append(str(exc))
    return errors


if __name__=='__main__':
    errors=validate();names=['staff','bell','statuette','seal','censer','scepter']
    print(json.dumps(dict(errors=errors,geometry={k:inspect_geometry(ROOT,k,'magic_bases')[1] for k in names})));raise SystemExit(bool(errors))
